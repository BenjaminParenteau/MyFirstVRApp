using UnityEngine;
using UnityEngine.XR.Interaction.Toolkit.Interactors;
using UnityEngine.XR.Interaction.Toolkit.Locomotion.Teleportation;

namespace HighStakes.Environment
{
    /// <summary>
    /// Does a standing player fit here? Used twice with the same numbers: once by <see cref="TeleportSurfaces"/> when it
    /// maps an area's walkable floor, and again by <see cref="TeleportSurface"/> on the exact point the ray landed on.
    /// </summary>
    public static class TeleportClearance
    {
        /// <summary>
        /// Everything a body can bump into: all layers except Ignore Raycast, the player's own PlayerBody layer and the
        /// teleport surfaces themselves (<see cref="TeleportSurfaces.Layer"/>).
        /// </summary>
        public static int BlockingLayers()
        {
            int mask = ~(1 << 2); // Ignore Raycast
            mask &= ~(1 << TeleportSurfaces.Layer);
            int body = LayerMask.NameToLayer("PlayerBody");
            if (body >= 0) mask &= ~(1 << body);
            return mask;
        }

        /// <summary>
        /// True when a <paramref name="radius"/> x <paramref name="height"/> capsule standing on <paramref name="floor"/>
        /// touches nothing. The capsule starts <paramref name="step"/> above the floor, so thresholds, kerbs and chips
        /// on the carpet (which the rig's CharacterController steps over anyway) don't count as blocked. Colliders under
        /// <paramref name="ignoreRoot"/> are skipped, which is how the player's own body is left out.
        /// </summary>
        public static bool IsClear(Vector3 floor, float radius, float height, float step, int layers,
            Collider[] buffer, Transform ignoreRoot)
        {
            var bottom = floor + Vector3.up * (step + radius);
            var top = floor + Vector3.up * Mathf.Max(height - radius, step + radius);
            int count = Physics.OverlapCapsuleNonAlloc(bottom, top, radius, buffer, layers, QueryTriggerInteraction.Ignore);
            if (count >= buffer.Length) return false; // more overlaps than we can read: treat as blocked

            for (int i = 0; i < count; i++)
            {
                var hit = buffer[i];
                if (hit == null) continue;
                if (ignoreRoot != null && hit.transform.IsChildOf(ignoreRoot)) continue;
                return false;
            }
            return true;
        }
    }

    /// <summary>
    /// One rectangle of walkable floor the teleport ray can land on, generated by <see cref="TeleportSurfaces"/>. The
    /// rectangles only cover cells a player fits in, but a landing point can sit half a cell from a cell's centre and
    /// props and NPCs move, so every request is re-checked with <see cref="TeleportClearance"/> at the exact point.
    /// </summary>
    public class TeleportSurface : TeleportationArea
    {
        readonly Collider[] overlaps = new Collider[16];

        /// <summary>Set by <see cref="TeleportSurfaces"/> from its own body size, so both use one set of numbers.</summary>
        public float bodyRadius = 0.25f;
        public float bodyHeight = StyleScale.FigureHeight;
        public float stepHeight = StyleScale.MaxStepHeight;

        /// <summary>The player rig, whose own colliders don't count as something in the way.</summary>
        public Transform rig;

        int layers = -1;

        protected override bool GenerateTeleportRequest(IXRInteractor interactor, RaycastHit hit, ref TeleportRequest request)
        {
            if (!base.GenerateTeleportRequest(interactor, hit, ref request)) return false;
            if (layers == -1) layers = TeleportClearance.BlockingLayers();
            return TeleportClearance.IsClear(hit.point, bodyRadius, bodyHeight, stepHeight, layers, overlaps, rig);
        }
    }
}
