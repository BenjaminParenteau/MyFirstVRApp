using System;

namespace HighStakes.Environment.Audio
{
    /// <summary>What the player is standing on, or what a sonar ping just bounced off.</summary>
    public enum SurfaceKind
    {
        Carpet,
        Wood,
        Concrete,
        Tile,
        Metal,
    }

    /// <summary>How a surface answers a sonar ping — soft swallows it, hard rings.</summary>
    public enum SurfaceHardness
    {
        Soft,
        Medium,
        Hard,
    }

    /// <summary>
    /// Works out what a surface is from the name of its material or object, with no Unity in it so it can be
    /// tested. Shared by two features on purpose: footsteps pick their cue from this, and the blackout mode's
    /// sonar picks its return cue from it, so "what is this made of" is answered in one place.
    /// <para>
    /// It is keyword matching on names, which sounds fragile but is the right trade here: the alternative is a
    /// component on every piece of geometry in six areas owned by four people. Names in this project are
    /// generated by builders and already descriptive (<c>Casino_Carpet</c>, <c>M_FeltGreen</c>,
    /// <c>Security_Concrete</c>, <c>Vault_TreadPlate</c>), so this costs nothing and needs no cooperation.
    /// Anything unrecognised reads as <see cref="SurfaceKind.Concrete"/> — unknown geometry is most likely
    /// structural, and a wrong-but-plausible footstep is better than silence.
    /// </para>
    /// </summary>
    public static class SurfaceLogic
    {
        /// <summary>Best guess at what a surface is, from a material name, object name, or both concatenated.</summary>
        public static SurfaceKind KindOf(string name)
        {
            if (string.IsNullOrEmpty(name)) return SurfaceKind.Concrete;
            string n = name.ToLowerInvariant();

            // Soft furnishings first: the casino floor is carpet and that is where players spend most of the game.
            if (Has(n, "carpet") || Has(n, "felt") || Has(n, "fabric") || Has(n, "leather")
                || Has(n, "velvet") || Has(n, "rug") || Has(n, "cloth"))
                return SurfaceKind.Carpet;

            if (Has(n, "wood") || Has(n, "panel") || Has(n, "oak") || Has(n, "rosewood")
                || Has(n, "parquet") || Has(n, "timber") || Has(n, "wainscot"))
                return SurfaceKind.Wood;

            if (Has(n, "marble") || Has(n, "tile") || Has(n, "ceramic") || Has(n, "stone")
                || Has(n, "granite"))
                return SurfaceKind.Tile;

            if (Has(n, "metal") || Has(n, "steel") || Has(n, "brass") || Has(n, "treadplate")
                || Has(n, "tread") || Has(n, "grate") || Has(n, "aluminium") || Has(n, "aluminum"))
                return SurfaceKind.Metal;

            if (Has(n, "concrete") || Has(n, "cinder") || Has(n, "block") || Has(n, "plaster")
                || Has(n, "asphalt") || Has(n, "sidewalk"))
                return SurfaceKind.Concrete;

            return SurfaceKind.Concrete;
        }

        static bool Has(string haystack, string needle) => haystack.IndexOf(needle, StringComparison.Ordinal) >= 0;

        /// <summary>The footstep cue for a surface. Slot D's namespace; see AudioBuilder's cue list.</summary>
        public static string FootstepCue(SurfaceKind kind)
        {
            switch (kind)
            {
                case SurfaceKind.Carpet: return "env.step.carpet";
                case SurfaceKind.Wood: return "env.step.wood";
                case SurfaceKind.Tile: return "env.step.tile";
                case SurfaceKind.Metal: return "env.step.metal";
                default: return "env.step.concrete";
            }
        }

        /// <summary>
        /// How hard a surface sounds. Carpet and felt swallow a ping; concrete, tile and metal ring. This is the
        /// information the blackout player is actually reading — "that is a wall" versus "that is a card table".
        /// </summary>
        public static SurfaceHardness HardnessOf(SurfaceKind kind)
        {
            switch (kind)
            {
                case SurfaceKind.Carpet: return SurfaceHardness.Soft;
                case SurfaceKind.Wood: return SurfaceHardness.Medium;
                default: return SurfaceHardness.Hard;
            }
        }

        /// <summary>The sonar return cue for a hardness. Medium rounds to the soft clip, pitched up by the cue.</summary>
        public static string SonarReturnCue(SurfaceHardness hardness)
            => hardness == SurfaceHardness.Hard ? "dark.sonar.return.hard" : "dark.sonar.return.soft";

        /// <summary>Convenience: straight from a surface name to the sonar cue it should answer with.</summary>
        public static string SonarReturnCueFor(string name) => SonarReturnCue(HardnessOf(KindOf(name)));
    }
}
